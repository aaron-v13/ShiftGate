"""ShiftGate Reference Review Screen (Screen 2)."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import pandas as pd
import streamlit as st

from app.lib import (
    check_missing_files,
    compare_review_decisions_to_bank,
    get_app_paths,
    load_review_decisions,
    load_run_metadata,
    render_header,
    render_run_info,
    save_review_decisions,
)

st.set_page_config(
    page_title="ShiftGate - Reference Review",
    page_icon="🔍",
    layout="wide",
)

paths = get_app_paths()
missing = check_missing_files(paths)
if missing:
    for m in missing:
        st.error(m)
    st.stop()

meta = load_run_metadata(paths.meta_path)
render_header(
    title="🔍 Reference Image Review",
    is_mock=paths.is_mock,
    subtitle="Review proposed candidate normal examples before reference bank incorporation",
)

if not paths.candidate_list_path.exists():
    st.error(
        f"Candidate list '{paths.candidate_list_path}' is missing. "
        f"This file is generated by System 1 (candidate pool generation)."
    )
    st.stop()

df_cand = pd.read_csv(paths.candidate_list_path)
saved_decisions = load_review_decisions(paths.review_decisions_path)


def get_placeholder_image(label: str, w: int = 240, h: int = 240) -> Image.Image:
    """Create a labelled placeholder image when raw asset file is not on disk."""
    img = Image.new("RGB", (w, h), color=(30, 41, 59))
    draw = ImageDraw.Draw(img)
    draw.rectangle([6, 6, w - 6, h - 6], outline=(100, 116, 139), width=2)
    draw.text((16, h // 2 - 10), label, fill=(241, 245, 249))
    return img


st.markdown(
    """
    Quality engineers must review proposed reference candidates. Approving normal boards adapts the station
    to the condition shift (`shift_a`), but accidentally approving a contaminant defect corrupts the reference bank.
    """
)

st.subheader("Proposed Candidates Pool")

current_choices: dict[str, str] = {}
cols_per_row = 2

for idx, row in df_cand.iterrows():
    img_id = str(row["image_id"])
    cond = str(row.get("condition", "N/A"))
    path_val = str(row.get("path", ""))

    with st.container(border=True):
        c_img, c_ctrl = st.columns([1, 2])

        with c_img:
            file_path = Path(path_val)
            if file_path.exists():
                try:
                    img = Image.open(file_path)
                    st.image(img, caption=img_id, use_container_width=True)
                except Exception:
                    st.image(get_placeholder_image(f"Image: {img_id}"), use_container_width=True)
            else:
                st.image(get_placeholder_image(f"Placeholder:\n{img_id}"), use_container_width=True)

        with c_ctrl:
            st.markdown(f"**Image ID:** `{img_id}`")
            st.caption(f"Condition: `{cond}` | Path: `{path_val}`")

            # Default selection from saved review decisions, fallback to 'approve'
            default_val = saved_decisions.get(img_id, "approve")
            choice = st.radio(
                f"Review decision for {img_id}",
                options=["approve", "reject"],
                index=0 if default_val == "approve" else 1,
                key=f"choice_{img_id}",
                horizontal=True,
            )
            current_choices[img_id] = choice

st.markdown("---")

c_btn, c_space = st.columns([1, 2])
with c_btn:
    if st.button("💾 Save Review Decisions", type="primary", use_container_width=True):
        save_review_decisions(current_choices, paths.review_decisions_path)
        st.success(f"Saved {len(current_choices)} decisions to `{paths.review_decisions_path}`.")

        # Compare choices to in_v3_bank
        notes = compare_review_decisions_to_bank(current_choices, df_cand)
        if notes:
            st.warning("⚠️ **Review Comparison Note:**")
            for note in notes:
                st.markdown(f"- {note}")
        else:
            st.info("✅ Your selections match the curated reference bank composition of `v3_candidate_reviewed`.")

render_run_info(meta, paths.is_mock)
